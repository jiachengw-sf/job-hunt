"""The local dashboard (``~/.jobhunt/dashboard.html``) and ``APPLICATIONS.md``.

Both are generated from the store on every run, sync and status change, so they never drift.
The dashboard is one self-contained file: no server, no network, nothing uploaded. Its data is
embedded as JSON and rendered with ``textContent`` (never as HTML), because company names and
titles come from postings.
"""

from __future__ import annotations

import json
from datetime import date
from typing import Any

from jobhunt.tracker.views import attention_count

STATUS_ORDER = ["Interviewing", "OA", "Applied", "Offer", "Rejected", "Withdrawn", "Skipped",
                "Prefilled", "New"]  # fmt: skip


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.0%}"


def _due(d: str) -> str:
    if not d:
        return ""
    day = date.fromisoformat(d)
    return f"{day:%a}, {day:%b} {day.day}"


# --- Markdown -----------------------------------------------------------------------------------


def _cell(s: Any) -> str:
    return str(s if s not in (None, "") else "—").replace("|", "\\|").replace("\n", " ")


def _link(v: dict[str, Any]) -> str:
    w = v["where_to_check"]
    return f"[{_cell(_host(w))}]({w})" if w.startswith("https://") else _cell(w)


def _host(url: str) -> str:
    from urllib.parse import urlsplit

    u = urlsplit(url)
    return (u.hostname or url) + ("/…" if u.path.strip("/") else "")


def render_markdown(views: list[dict[str, Any]], s: dict[str, Any], *, generated: str) -> str:
    rate = _pct(s["interview_rate"])
    statuses = ", ".join(f"{k} {n}" for k, n in _ordered(s["by_status"])) or "none yet"
    out = [
        "# Applications",
        "",
        f"_Generated by jobhunt {generated}. Edits here are overwritten; change things in the "
        "tracker sheet or with `jobhunt app`._",
        "",
        "## Summary",
        "",
        f"- **{s['total']}** applications: {statuses}",
        f"- This week: **{s['this_week']}** · this month: **{s['this_month']}**",
        f"- Interview rate: **{rate}** ({s['interviews']} of {s['total']})",
        f"- Waiting to hear back: **{s['waiting']}**",
        "",
        "## Needs attention",
        "",
    ]
    items = _attention_items(s)
    out += [f"- {i}" for i in items] or ["Nothing right now."]
    out.append("")
    for status, group in _groups(views):
        out += [
            f"## {status} ({len(group)})",
            "",
            "| Company | Position | Applied | Days | Where to check | Next step |",
            "|---|---|---|---|---|---|",
        ]
        out += [
            f"| {_cell(v['company'])} | {_cell(v['position'])} | "
            f"{_cell(v['applied'])} | "
            f"{v['days_since_applied']} | {_link(v)} | {_cell(v['next_step'])} |"
            for v in group
        ]
        out.append("")
    if not views:
        out += ["No applications yet. Record one with `jobhunt applied <job id or URL>`.", ""]
    return "\n".join(out)


def _ordered(by_status: dict[str, int]) -> list[tuple[str, int]]:
    rank = {s: i for i, s in enumerate(STATUS_ORDER)}
    return sorted(by_status.items(), key=lambda kv: rank.get(kv[0], 99))


def _groups(views: list[dict[str, Any]]) -> list[tuple[str, list[dict[str, Any]]]]:
    by: dict[str, list[dict[str, Any]]] = {}
    for v in views:  # views are newest first already
        by.setdefault(v["status"], []).append(v)
    return [(st, by[st]) for st, _ in _ordered({k: len(g) for k, g in by.items()})]


def _attention_items(s: dict[str, Any]) -> list[str]:
    items = [
        f"Interview: {v['company']} — {v['position']}, {v['interview']['when']}"
        + (f" ({v['interview']['label']})" if v["interview"]["label"] else "")
        for v in s["upcoming_interviews"]
    ]
    items += [
        f"Deadline: {v['company']} — {v['deadline']['label'] or 'deadline'}, "
        f"{v['deadline']['when']}"
        for v in s["deadlines_this_week"]
    ]
    items += [
        f"Follow-up due: {v['company']} — {v['position']} (due {_due(v['followup_due_on'])}; "
        "`jobhunt outreach draft` drafts one, you send it)"
        for v in s["followups_due"]
    ]
    items += [
        f"Likely no response: {v['company']} — {v['position']} ({v['days_without_update']} days "
        "with no update; status unchanged)"
        for v in s["stale"]
    ]
    return items


# --- HTML ---------------------------------------------------------------------------------------


def _public(v: dict[str, Any]) -> dict[str, Any]:
    """What the page shows. No answer values (only labels), no job keys."""
    keys = ["app_id", "company", "position", "team", "location", "employment", "pay", "applied",
            "applied_at", "method", "recorded_via", "status", "last_update", "last_update_at",
            "days_since_applied", "where_to_check", "status_check_url", "status_check_method",
            "status_check_note", "login_email", "confirmation_id", "referral_contact",
            "recruiter", "next_step", "followup_due_on", "outcome", "notes", "resume_file",
            "posting_url", "folder", "has_screenshot", "has_jd", "attention", "dates",
            "stale", "followup_due"]  # fmt: skip
    out = {k: v[k] for k in keys}
    out["followup_due_text"] = _due(v["followup_due_on"])
    out["history"] = [{k: h[k] for k in ("when", "from", "to", "who", "note")}
                      for h in v["history"]]  # fmt: skip
    out["sent"] = [s["label"] + (" (sensitive)" if s["sensitive"] else "") for s in v["submitted"]]
    return out


def render_html(views: list[dict[str, Any]], s: dict[str, Any], *, generated: str) -> str:
    data = {
        "generated": generated,
        "summary": {
            "total": s["total"],
            "by_status": dict(_ordered(s["by_status"])),
            "this_week": s["this_week"],
            "this_month": s["this_month"],
            "interviews": s["interviews"],
            "interview_rate": _pct(s["interview_rate"]),
            "waiting": s["waiting"],
            "needs_attention": attention_count(s),
        },
        "attention": _attention_items(s),
        "apps": [_public(v) for v in views],
    }
    blob = json.dumps(data, ensure_ascii=False).replace("<", "\\u003c").replace(">", "\\u003e")
    return _PAGE.replace("__DATA__", blob.replace("&", "\\u0026"))


